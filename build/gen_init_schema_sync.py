#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
dataforge init 脚本「既有库自愈段」生成器

背景
    init/dataforge-*.sql 是 schema 的唯一来源（2026-10-09 起 sql/migrate/ 已整体删除）。
    但 CREATE TABLE IF NOT EXISTS 只解决「缺表」，解决不了「表在、列不在」：
    老库升级新镜像后新加的列永远补不上去，线上直接报
    `column "xxx" does not exist`（例如 table_metadata.business_owner）。
    又因为 init-dataforge.sh 原先「见到 sys_user 表就整段跳过」，连补表都做不到。

本生成器干什么
    从每份 init 脚本**自身的建表段**解析出全部列与约束，生成一段幂等的「补齐」SQL，
    插到建表段**之前**，使整份脚本可反复执行并把老库收敛到当前定义：

      PostgreSQL : DO 块 + information_schema / pg_constraint 存在性判断 + 动态 ALTER
      MySQL      : 两个存储过程（df_sync_add_column / df_sync_add_index）+ CALL 列表
      H2         : ALTER TABLE ... ADD COLUMN IF NOT EXISTS / ADD CONSTRAINT IF NOT EXISTS

    索引无需生成：PG/H2 的 `CREATE INDEX IF NOT EXISTS`、种子数据的
    `ON CONFLICT DO NOTHING` / `INSERT IGNORE` / `WHERE NOT EXISTS` 本身就幂等。

两个必须守住的实现要点（踩过坑，别改回去）
    1. **位置：必须放在建表段之前。**
       COMMENT ON / CREATE INDEX 紧跟在各表建表之后。老库缺列时，这些语句会先报错；
       在 PostgreSQL 里更会 abort 整个事务，导致后续语句（包括原设计放在文件末尾的
       补齐段）全部不执行 —— 脚本"看起来跑了"，实际什么都没补上。
    2. **PostgreSQL 的补齐段必须在 `BEGIN;` 之前**，即自事务之外执行。
       否则一旦后面任何语句出错，事务回滚会把补好的列一起撤销。
    3. **容错：每条 ALTER 各自包 EXCEPTION**（PG）/ 逐条 CALL（MySQL）。
       单列补不上（例如旧表有数据、新列是 NOT NULL 无默认值）只降级成 WARNING，
       绝不 abort 脚本，也不影响其它列。

用法
    python3 build/gen_init_schema_sync.py            # 生成/刷新 4 份脚本的补齐段
    python3 build/gen_init_schema_sync.py --check    # 只检查是否需要重新生成（CI 用，需刷新则退出码 1）

约束
    * 只处理 init 脚本里已有的信息，不引入任何外部 schema 来源。
    * 手改上方 DDL 后必须重跑本脚本，否则补齐段与实际定义会脱节。
"""

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
INIT_DIR = REPO / "src" / "main" / "resources" / "sql" / "init"

DIALECT_BY_FILE = {
    "dataforge-postgresql.sql": "postgresql",
    "dataforge-mysql.sql": "mysql",
    "dataforge-mariadb.sql": "mysql",
    "dataforge-h2.sql": "h2",
}

BEGIN_MARK = "-- >>> BEGIN AUTO-GENERATED SCHEMA SYNC (generated by build/gen_init_schema_sync.py, DO NOT EDIT) >>>"
END_MARK = "-- <<< END AUTO-GENERATED SCHEMA SYNC <<<"

TABLE_RE = re.compile(r"^CREATE TABLE IF NOT EXISTS\s+`?([A-Za-z_][A-Za-z0-9_]*)`?\s*\(\s*$")
MYSQL_UNIQUE_KEY_RE = re.compile(r"^UNIQUE KEY\s+`([^`]+)`\s*\((.*)\)\s*$", re.I)
MYSQL_KEY_RE = re.compile(r"^KEY\s+`([^`]+)`\s*\((.*)\)\s*$", re.I)
NAMED_CONSTRAINT_RE = re.compile(
    r"^CONSTRAINT\s+([A-Za-z_][A-Za-z0-9_]*)\s+(UNIQUE|CHECK)\s+(.*?)\s*$", re.I
)
MYSQL_COL_RE = re.compile(r"^`([^`]+)`\s*(.*)$")
PLAIN_COL_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s+(.*)$")
KEYWORD_LINE_RE = re.compile(
    r"^(PRIMARY KEY|CONSTRAINT|UNIQUE KEY|UNIQUE|KEY|FOREIGN KEY|INDEX|CHECK|FULLTEXT)\b", re.I
)
CREATE_TABLE_RE = re.compile(r"^CREATE TABLE IF NOT EXISTS\b", re.M)
BEGIN_TX_RE = re.compile(r"^BEGIN;\s*$", re.M)


def q(literal: str) -> str:
    """转义成单引号字符串字面量的内容。"""
    return literal.replace("'", "''")


def split_mysql_comment(definition: str):
    """MySQL 列定义把 COMMENT 内联在末尾，拆出来单独传给存储过程。"""
    m = re.search(r"\sCOMMENT\s'(.*)'\s*$", definition, re.S)
    if not m:
        return definition.strip(), ""
    return definition[: m.start()].strip(), m.group(1).replace("''", "'")


def remove_block(text: str) -> str:
    """摘掉标记之间的补齐段（无论它在文件哪个位置），只留 DDL 主体。"""
    i = text.find(BEGIN_MARK)
    if i < 0:
        return text
    j = text.find(END_MARK, i)
    if j < 0:
        return text[:i]
    return text[:i] + text[j + len(END_MARK):]


def parse(path: Path):
    """从 init 脚本的建表段解析出 (表 -> 列/约束)。"""
    # 先摘掉上一次生成的补齐段，避免把补齐段里的字面量当成 DDL
    text = remove_block(path.read_text(encoding="utf-8"))
    lines = text.splitlines()
    tables = {}
    order = []
    warnings = []
    i = 0
    while i < len(lines):
        m = TABLE_RE.match(lines[i].strip())
        if not m:
            i += 1
            continue
        table = m.group(1)
        columns = []
        constraints = []
        i += 1
        while i < len(lines) and not lines[i].lstrip().startswith(")"):
            raw = lines[i].strip()
            i += 1
            if not raw or raw.startswith("--"):
                continue
            raw = raw.rstrip(",").strip()
            if not raw:
                continue
            if KEYWORD_LINE_RE.match(raw):
                cu = MYSQL_UNIQUE_KEY_RE.match(raw)
                ck = MYSQL_KEY_RE.match(raw)
                cn = NAMED_CONSTRAINT_RE.match(raw)
                if cu:
                    constraints.append(("unique", cu.group(1), cu.group(2).strip()))
                elif ck:
                    constraints.append(("index", ck.group(1), ck.group(2).strip()))
                elif cn:
                    kind = cn.group(2).upper()
                    suffix = ("UNIQUE " if kind == "UNIQUE" else "CHECK ") + cn.group(3).strip()
                    constraints.append((kind.lower(), cn.group(1), suffix))
                elif not re.match(r"^PRIMARY KEY\b", raw, re.I):
                    warnings.append(f"{path.name}: {table} 未识别的约束行 -> {raw}")
                continue
            cm = MYSQL_COL_RE.match(raw) or PLAIN_COL_RE.match(raw)
            if not cm:
                warnings.append(f"{path.name}: {table} 未识别的列定义 -> {raw}")
                continue
            name, definition = cm.group(1), cm.group(2).strip()
            comment = ""
            if cm.re is MYSQL_COL_RE:
                definition, comment = split_mysql_comment(definition)
            if not definition:
                warnings.append(f"{path.name}: {table}.{name} 定义为空")
                continue
            columns.append((name, definition, comment))
        i += 1
        if not columns:
            warnings.append(f"{path.name}: 表 {table} 未解析到任何列")
        tables[table] = {"columns": columns, "constraints": constraints}
        order.append(table)
    return tables, order, warnings


HEADER = [
    "-- ------------------------------------------------------------------",
    "-- 既有库自动补齐（幂等）：把「表已存在但缺列 / 缺约束」的历史库拉到最新定义",
    "--",
    "--   为什么需要：CREATE TABLE IF NOT EXISTS 只补「缺表」，对「表在、列不在」无能为力。",
    "--   本段让整份 init 脚本可以反复执行，老库每次启动都自动收敛到下方的最新定义，",
    "--   无需任何独立的迁移脚本。索引与种子数据无需在此重复：文件里的",
    "--   CREATE INDEX IF NOT EXISTS 与幂等种子写入本身就是可重跑的。",
    "--",
    "--   ⚠ 位置不能挪：必须放在建表段之前。COMMENT ON / CREATE INDEX 紧跟各表建表，",
    "--     老库缺列时它们会先报错，PostgreSQL 里更会 abort 整个事务，",
    "--     把后续语句（包括本段）全部带没 —— 脚本看似跑过了，实际什么都没补上。",
    "--   ⚠ 每条 ALTER 都各自兜异常：单列补不上只降级为 WARNING，不 abort 脚本。",
    "--",
    "--   ⚠ 由 build/gen_init_schema_sync.py 生成，请勿手改；改完 DDL 后重跑生成器。",
    "-- ------------------------------------------------------------------",
    "",
]


def gen_postgresql(tables, order):
    out = list(HEADER)
    out.append("DO $$")
    out.append("DECLARE r RECORD;")
    out.append("BEGIN")
    out.append("  FOR r IN SELECT * FROM (VALUES")
    rows = [
        f"    ('{q(t)}', '{q(n)}', '{q(d)}')"
        for t in order
        for n, d, _ in tables[t]["columns"]
    ]
    out.append(",\n".join(rows))
    out.append("  ) AS t(tbl, col, defn) LOOP")
    out.append("    IF EXISTS (SELECT 1 FROM information_schema.tables")
    out.append("                WHERE table_schema = current_schema() AND table_name = r.tbl)")
    out.append("       AND NOT EXISTS (SELECT 1 FROM information_schema.columns")
    out.append("                        WHERE table_schema = current_schema()")
    out.append("                          AND table_name = r.tbl AND column_name = r.col) THEN")
    out.append("      BEGIN")
    out.append("        EXECUTE format('ALTER TABLE %I ADD COLUMN %I %s', r.tbl, r.col, r.defn);")
    out.append("      EXCEPTION WHEN OTHERS THEN")
    out.append("        RAISE WARNING 'schema-sync: 补列 %.% 失败，已跳过: %', r.tbl, r.col, SQLERRM;")
    out.append("      END;")
    out.append("    END IF;")
    out.append("  END LOOP;")
    out.append("END $$;")
    out.append("")
    out.append("DO $$")
    out.append("DECLARE r RECORD;")
    out.append("BEGIN")
    out.append("  FOR r IN SELECT * FROM (VALUES")
    rows = [
        f"    ('{q(n)}', '{q(t)}', '{q(d)}')"
        for t in order
        for _, n, d in tables[t]["constraints"]
    ] or ["    (NULL, NULL, NULL)"]
    out.append(",\n".join(rows))
    out.append("  ) AS t(cname, tbl, defn) LOOP")
    out.append("    IF r.cname IS NOT NULL")
    out.append("       AND to_regclass(format('%I.%I', current_schema(), r.tbl)) IS NOT NULL")
    out.append("       AND NOT EXISTS (SELECT 1 FROM pg_constraint")
    out.append("                        WHERE conname = r.cname")
    out.append("                          AND conrelid = to_regclass(format('%I.%I', current_schema(), r.tbl))) THEN")
    out.append("      BEGIN")
    out.append("        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I %s', r.tbl, r.cname, r.defn);")
    out.append("      EXCEPTION WHEN OTHERS THEN")
    out.append("        RAISE WARNING 'schema-sync: 补约束 % 失败，已跳过: %', r.cname, SQLERRM;")
    out.append("      END;")
    out.append("    END IF;")
    out.append("  END LOOP;")
    out.append("END $$;")
    return "\n".join(out) + "\n"


def gen_mysql(tables, order):
    out = list(HEADER)
    out.append("-- ⚠ MySQL 不支持 ADD COLUMN IF NOT EXISTS，故用存储过程守卫；")
    out.append("--   本段含 DELIMITER，必须用 mysql CLI 执行（IDE/JDBC 不认识 DELIMITER）。")
    out.append("")
    out.append("DROP PROCEDURE IF EXISTS df_sync_add_column;")
    out.append("DELIMITER $$")
    out.append("CREATE PROCEDURE df_sync_add_column(")
    out.append("  IN p_table VARCHAR(64), IN p_column VARCHAR(64),")
    out.append("  IN p_definition VARCHAR(2000), IN p_comment VARCHAR(1000))")
    out.append("BEGIN")
    out.append("  IF EXISTS (SELECT 1 FROM information_schema.TABLES")
    out.append("              WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = p_table)")
    out.append("     AND NOT EXISTS (SELECT 1 FROM information_schema.COLUMNS")
    out.append("                      WHERE TABLE_SCHEMA = DATABASE()")
    out.append("                        AND TABLE_NAME = p_table AND COLUMN_NAME = p_column) THEN")
    out.append("    IF p_comment IS NULL OR p_comment = '' THEN")
    out.append("      SET @ddl = CONCAT('ALTER TABLE `', p_table, '` ADD COLUMN `', p_column, '` ', p_definition);")
    out.append("    ELSE")
    out.append("      SET @ddl = CONCAT('ALTER TABLE `', p_table, '` ADD COLUMN `', p_column, '` ',")
    out.append("                        p_definition, ' COMMENT ', QUOTE(p_comment));")
    out.append("    END IF;")
    out.append("    PREPARE df_stmt FROM @ddl;")
    out.append("    EXECUTE df_stmt;")
    out.append("    DEALLOCATE PREPARE df_stmt;")
    out.append("  END IF;")
    out.append("END$$")
    out.append("DELIMITER ;")
    out.append("")
    out.append("DROP PROCEDURE IF EXISTS df_sync_add_index;")
    out.append("DELIMITER $$")
    out.append("CREATE PROCEDURE df_sync_add_index(")
    out.append("  IN p_table VARCHAR(64), IN p_index VARCHAR(64),")
    out.append("  IN p_unique TINYINT, IN p_columns VARCHAR(1000))")
    out.append("BEGIN")
    out.append("  IF EXISTS (SELECT 1 FROM information_schema.TABLES")
    out.append("              WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = p_table)")
    out.append("     AND NOT EXISTS (SELECT 1 FROM information_schema.STATISTICS")
    out.append("                      WHERE TABLE_SCHEMA = DATABASE()")
    out.append("                        AND TABLE_NAME = p_table AND INDEX_NAME = p_index) THEN")
    out.append("    SET @ddl = CONCAT('ALTER TABLE `', p_table, '` ADD ',")
    out.append("                      IF(p_unique = 1, 'UNIQUE ', ''), 'INDEX `', p_index, '` (', p_columns, ')');")
    out.append("    PREPARE df_stmt FROM @ddl;")
    out.append("    EXECUTE df_stmt;")
    out.append("    DEALLOCATE PREPARE df_stmt;")
    out.append("  END IF;")
    out.append("END$$")
    out.append("DELIMITER ;")
    out.append("")
    for t in order:
        for name, definition, comment in tables[t]["columns"]:
            out.append(
                f"CALL df_sync_add_column('{q(t)}', '{q(name)}', '{q(definition)}', '{q(comment)}');"
            )
    out.append("")
    for t in order:
        for kind, name, definition in tables[t]["constraints"]:
            out.append(
                f"CALL df_sync_add_index('{q(t)}', '{q(name)}', {'1' if kind == 'unique' else '0'}, '{q(definition)}');"
            )
    out.append("")
    out.append("DROP PROCEDURE IF EXISTS df_sync_add_column;")
    out.append("DROP PROCEDURE IF EXISTS df_sync_add_index;")
    return "\n".join(out) + "\n"


def gen_h2(tables, order):
    out = list(HEADER)
    out.append("-- ⚠ H2 的 `ADD COLUMN IF NOT EXISTS` 只保护「列」，不保护「表」：表不存在时会直接报")
    out.append("--   Table not found 并中断脚本，故必须写成 `ALTER TABLE IF EXISTS ...`。")
    out.append("")
    for t in order:
        for name, definition, _ in tables[t]["columns"]:
            out.append(f"ALTER TABLE IF EXISTS {t} ADD COLUMN IF NOT EXISTS {name} {definition};")
    out.append("")
    for t in order:
        for _, name, definition in tables[t]["constraints"]:
            out.append(f"ALTER TABLE IF EXISTS {t} ADD CONSTRAINT IF NOT EXISTS {name} {definition};")
    return "\n".join(out) + "\n"


GENERATORS = {"postgresql": gen_postgresql, "mysql": gen_mysql, "h2": gen_h2}


def strip_block(text: str) -> str:
    """摘掉上一次生成的补齐段（含标记行与随后的空行）。"""
    i = text.find(BEGIN_MARK)
    if i < 0:
        return text
    j = text.find(END_MARK, i)
    if j < 0:
        return text[:i].rstrip("\n") + "\n"
    j += len(END_MARK)
    head = text[:i].rstrip("\n")
    tail = text[j:].lstrip("\n")
    return head + "\n\n" + tail


def insert_block(text: str, dialect: str, block: str) -> str:
    """按方言把补齐段插到建表段之前（PG 还要放到 BEGIN; 之前，脱离事务）。"""
    if dialect == "postgresql":
        m = BEGIN_TX_RE.search(text)
        if not m:
            raise SystemExit("dataforge-postgresql.sql 里找不到 `BEGIN;`，无法定位补齐段位置")
        pos = m.start()
    else:
        m = CREATE_TABLE_RE.search(text)
        if not m:
            raise SystemExit("找不到首个 CREATE TABLE，无法定位补齐段位置")
        pos = m.start()
    return text[:pos] + BEGIN_MARK + "\n" + block + END_MARK + "\n\n" + text[pos:]


def main() -> int:
    check_only = "--check" in sys.argv[1:]
    changed = []
    for filename, dialect in DIALECT_BY_FILE.items():
        path = INIT_DIR / filename
        original = path.read_text(encoding="utf-8")
        tables, order, warnings = parse(path)
        for w in warnings:
            print(f"  [warn] {w}")
        block = GENERATORS[dialect](tables, order)
        updated = insert_block(strip_block(original), dialect, block)
        ncols = sum(len(tables[t]["columns"]) for t in order)
        ncons = sum(len(tables[t]["constraints"]) for t in order)
        status = "unchanged" if updated == original else "UPDATED"
        if updated != original:
            changed.append(filename)
            if not check_only:
                path.write_text(updated, encoding="utf-8")
        print(
            f"  {filename:<28} dialect={dialect:<11} 表={len(order):<3} 列={ncols:<4} 约束={ncons:<3} -> {status}"
        )
    if check_only and changed:
        print("\n以下文件需要重新生成补齐段：" + ", ".join(changed))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
